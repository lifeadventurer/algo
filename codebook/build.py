#!/usr/bin/env python3
"""Generate the contents, compile the LaTeX book, and pack Overleaf sources."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parent.parent
DIRECTORIES = [
    ("template", "Contest starters"),
    ("data", "Data structures"),
    ("graph", "Graphs and trees"),
    ("string", "Strings"),
    ("numeric", "Number theory and algebra"),
    ("geometry", "Geometry"),
    ("dp", "Dynamic programming"),
    ("misc", "IO and utilities"),
]


def escape(s):
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
                    "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(replacements.get(c, c) for c in s)


def generate():
    catalog = json.loads((ROOT / "codebook/catalog.json").read_text())
    sources = {p.relative_to(ROOT).as_posix()
               for directory, _ in DIRECTORIES
               for p in (ROOT / directory).rglob("*.cpp")}
    sources.add("debug.h")
    stale = set(catalog) - sources
    if stale:
        raise SystemExit(f"Catalog references missing sources: {sorted(stale)}")
    lines = ["% Generated by codebook/build.py; edit catalog.json and sources."]
    printed = []
    for directory, title in DIRECTORIES:
        lines.append(r"\section{" + escape(title) + "}")
        paths = [p for p in catalog if p.startswith(directory + "/")]
        paths += sorted(p for p in sources - set(catalog)
                        if p.startswith(directory + "/"))
        if directory == "misc":
            paths.append("debug.h")
        for path in paths:
            title, complexity, note, usage = catalog.get(path, [
                Path(path).stem.replace("_", " ").title(), "New template",
                "Add complexity, indexing, and preconditions in codebook/catalog.json.",
                "Add a usage example in codebook/catalog.json."])
            source = (ROOT / path).read_bytes()
            count = len(source.splitlines())
            fingerprint = hashlib.sha256(source).hexdigest()[:12]
            entry = (r"\entry{" + escape(title) + "}{" + path + "}{"
                     + escape(complexity) + "}{" + escape(note) + "}{"
                     + escape(usage) + "}{" + str(count) + "}{" + fingerprint
                     + "}{" + str(len(printed) + 1) + "}")
            # Keep short snippets with their headings; longer code may split.
            if count <= 25:
                entry = (r"\par\noindent\begin{minipage}{\linewidth}" + "\n"
                         + entry + "\n" + r"\end{minipage}\par")
            lines.append(entry)
            printed.append(path)
    assert len(printed) == len(set(printed)) and set(printed) == sources
    (ROOT / "codebook/contents.tex").write_text("\n".join(lines) + "\n")
    records = ["% Generated source identities; LaTeX resolves their pages from labels."]
    records += [r"\RegisterSnippet{" + str(index) + "}{" + escape(Path(path).stem) + "}"
                for index, path in enumerate(printed, 1)]
    (ROOT / "codebook/navigation.tex").write_text("\n".join(records) + "\n")
    print(f"Included every template: {len(printed)} sources.", flush=True)
    return printed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate-only", action="store_true",
                        help="Generate includes and source ZIP without compiling")
    parser.add_argument("--fingerprint", metavar="SOURCE",
                        help="Print a source file's exact-byte SHA-256 fingerprint")
    args = parser.parse_args()
    if args.fingerprint:
        path = (ROOT / args.fingerprint).resolve()
        path.relative_to(ROOT)
        print(hashlib.sha256(path.read_bytes()).hexdigest()[:12])
        return
    sources = generate()
    out = ROOT / "output/pdf"
    out.mkdir(parents=True, exist_ok=True)
    if not args.generate_only:
        engine = shutil.which("pdflatex")
        if not engine:
            raise SystemExit("pdflatex is missing. Install TeX Live/MacTeX or upload the source ZIP to Overleaf (use --generate-only first).")
        command = [engine, "-interaction=nonstopmode", "-halt-on-error",
                   "-file-line-error", f"-output-directory={out}",
                   "codebook/icpc-codebook.tex"]
        previous = None
        for _ in range(6):
            result = subprocess.run(command, cwd=ROOT, text=True,
                                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            if result.returncode:
                print(result.stdout[-10000:])
                raise SystemExit(result.returncode)
            state = tuple((out / f"icpc-codebook.{suffix}").read_bytes()
                          for suffix in ("aux", "toc", "out"))
            if state == previous:
                break
            previous = state
        else:
            raise SystemExit("PDF references did not stabilize after six passes.")
        log = (out / "icpc-codebook.log").read_text()
        overflow = [line for line in log.splitlines() if "Overfull" in line]
        if overflow:
            print("Layout warnings:\n" + "\n".join(overflow))
        if shutil.which("pdfinfo"):
            info = subprocess.check_output(["pdfinfo", str(out / "icpc-codebook.pdf")], text=True)
            print("\n".join(line for line in info.splitlines()
                            if line.startswith(("Pages:", "Page size:", "File size:"))))
        print(f"PDF: {out / 'icpc-codebook.pdf'}")
    bundle = out / "icpc-codebook-source.zip"
    files = sources + ["codebook/icpc-codebook.tex", "codebook/contents.tex", "codebook/navigation.tex",
                       "codebook/quick-reference.tex", "codebook/formulas.tex",
                       "codebook/contest.vimrc",
                       "codebook/catalog.json", "codebook/build.py", "codebook/README.md",
                       "codebook/verify.py", "codebook/tests/algorithms.cc",
                       "codebook/tests/new_topics.cc", "codebook/tests/navigation.py",
                       ".clang-format"]
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as z:
        for path in files:
            z.write(ROOT / path, path)
    print(f"LaTeX source bundle: {bundle}")


if __name__ == "__main__":
    main()
